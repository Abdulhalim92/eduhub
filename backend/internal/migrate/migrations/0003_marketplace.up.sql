-- 0003_marketplace — магазин методик (B2B): курсы, доступы центров, заявки.
-- Программа курса (модули→уроки→материалы) хранится как JSONB-документ (дерево, не реляционные запросы).
-- Деньги: BIGINT в дирамах. Время: TIMESTAMPTZ. Таблицы создаются пустыми — обычный CREATE INDEX.

CREATE TABLE courses (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title           TEXT NOT NULL,
    direction       TEXT NOT NULL,
    description     TEXT NOT NULL DEFAULT '',
    note            TEXT NOT NULL DEFAULT '',
    status          TEXT NOT NULL CHECK (status IN ('draft', 'published', 'private')),
    price_diram     BIGINT NOT NULL DEFAULT 0 CHECK (price_diram >= 0),
    owner_center_id BIGINT REFERENCES centers(id),  -- NULL — курс платформы; иначе собственный курс центра
    lessons         INTEGER NOT NULL DEFAULT 0,
    tests           INTEGER NOT NULL DEFAULT 0,
    buyers_other    INTEGER NOT NULL DEFAULT 0,      -- демо: сколько центров купили «вне» этого прототипа
    content         JSONB NOT NULL DEFAULT '{"modules":[]}',
    content_seq     BIGINT NOT NULL DEFAULT 1,       -- счётчик id узлов программы
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_courses_owner ON courses (owner_center_id);
CREATE INDEX idx_courses_status ON courses (status);
CREATE INDEX idx_courses_direction ON courses (direction);
-- Уникальность названия: отдельно среди платформенных и среди собственных у одного центра.
CREATE UNIQUE INDEX uq_courses_platform_title ON courses (lower(title)) WHERE owner_center_id IS NULL;
CREATE UNIQUE INDEX uq_courses_center_title ON courses (owner_center_id, lower(title)) WHERE owner_center_id IS NOT NULL;

CREATE TABLE course_access (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    center_id      BIGINT NOT NULL REFERENCES centers(id),
    course_id      BIGINT NOT NULL REFERENCES courses(id),
    source         TEXT NOT NULL CHECK (source IN ('invoice', 'balance', 'bonus')),
    invoice_id     TEXT,
    reason         TEXT NOT NULL DEFAULT '',
    granted_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    status         TEXT NOT NULL CHECK (status IN ('active', 'revoked')),
    revoked_at     TIMESTAMPTZ,
    revoke_reason  TEXT NOT NULL DEFAULT '',
    version_lessons INTEGER NOT NULL DEFAULT 0,      -- версия курса на момент передачи (BR-015)
    version_tests   INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX idx_course_access_center ON course_access (center_id);
CREATE INDEX idx_course_access_course ON course_access (course_id);
-- Один активный доступ на (центр, курс): владеть курсом дважды нельзя (BR-014).
CREATE UNIQUE INDEX uq_course_access_active ON course_access (center_id, course_id) WHERE status = 'active';

CREATE TABLE course_requests (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    center_id  BIGINT NOT NULL REFERENCES centers(id),
    course_id  BIGINT NOT NULL REFERENCES courses(id),
    status     TEXT NOT NULL CHECK (status IN ('new', 'invoiced', 'fulfilled', 'rejected')),
    note       TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    invoice_id TEXT,
    reason     TEXT NOT NULL DEFAULT '',
    decided_at TIMESTAMPTZ
);
CREATE INDEX idx_course_requests_center ON course_requests (center_id);
CREATE INDEX idx_course_requests_course ON course_requests (course_id);
CREATE INDEX idx_course_requests_status ON course_requests (status);
