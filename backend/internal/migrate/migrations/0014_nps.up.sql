-- 0014_nps — оценка качества уроков (LRN-PRN-040, CTR-ANL-010): ежемесячный опрос и опрос после
-- пробного занятия, 1–5 звёзд. Низкая оценка (1–3) помечается alert для сигнала директору.
-- Время — TIMESTAMPTZ; период опроса — первое число месяца (DATE).

CREATE TABLE nps_responses (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id        BIGINT NOT NULL REFERENCES centers(id),
    student_id       BIGINT NOT NULL REFERENCES students(id),
    rater_account_id BIGINT REFERENCES accounts(id),   -- кто поставил (ученик или родитель)
    kind             TEXT NOT NULL CHECK (kind IN ('monthly', 'trial')),
    period           DATE,                              -- для monthly: первое число месяца
    stars            INTEGER NOT NULL CHECK (stars BETWEEN 1 AND 5),
    comment          TEXT NOT NULL DEFAULT '',
    alert            BOOLEAN NOT NULL DEFAULT FALSE,    -- оценка 1–3 — тревожный сигнал
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);
-- Одна ежемесячная оценка на ученика в месяц (повтор за тот же период отклоняется).
CREATE UNIQUE INDEX uq_nps_monthly ON nps_responses (tenant_id, student_id, period) WHERE kind = 'monthly';
CREATE INDEX idx_nps_tenant ON nps_responses (tenant_id, created_at);
