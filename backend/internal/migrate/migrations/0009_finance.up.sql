-- 0009_finance — касса центра (CTR-FIN) и зарплаты преподавателей (CTR-PAY).
-- Реальные деньги центра, изолированные от платформы (BR-022): отдельно от centers.balance_diram.
-- Деньги — BIGINT в дирамах (money.md). Время — TIMESTAMPTZ.

CREATE TABLE cash_settings (
    center_id        BIGINT PRIMARY KEY REFERENCES centers(id),
    coin_rate        INTEGER NOT NULL DEFAULT 10 CHECK (coin_rate >= 1),   -- баллов за 1 сомони
    max_discount_pct INTEGER NOT NULL DEFAULT 25 CHECK (max_discount_pct BETWEEN 0 AND 100),
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE cash_shifts (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    center_id    BIGINT NOT NULL REFERENCES centers(id),
    cashier_name TEXT NOT NULL DEFAULT '',
    opened_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    closed_at    TIMESTAMPTZ,
    status       TEXT NOT NULL CHECK (status IN ('open', 'closed'))
);
CREATE INDEX idx_cash_shifts_center ON cash_shifts (center_id);

CREATE SEQUENCE receipt_no_seq START 1000;

CREATE TABLE payments (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    center_id     BIGINT NOT NULL REFERENCES centers(id),
    student_id    BIGINT NOT NULL REFERENCES students(id),
    group_id      BIGINT REFERENCES groups(id),
    purpose       TEXT NOT NULL DEFAULT '',
    amount_diram  BIGINT NOT NULL CHECK (amount_diram >= 0),
    discount_coin INTEGER NOT NULL DEFAULT 0,
    discount_diram BIGINT NOT NULL DEFAULT 0,
    final_diram   BIGINT NOT NULL CHECK (final_diram >= 0),
    method        TEXT NOT NULL CHECK (method IN ('cash', 'pos', 'card')),
    lessons       INTEGER NOT NULL DEFAULT 0 CHECK (lessons >= 0),
    shift_id      BIGINT REFERENCES cash_shifts(id),
    status        TEXT NOT NULL CHECK (status IN ('paid', 'refunded')),
    refund_reason TEXT NOT NULL DEFAULT '',
    receipt_no    TEXT NOT NULL,
    cashier_name  TEXT NOT NULL DEFAULT '',
    refunded_at   TIMESTAMPTZ,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_payments_center ON payments (center_id);
CREATE INDEX idx_payments_shift ON payments (shift_id);
CREATE INDEX idx_payments_student ON payments (student_id);

-- Оплаченные, ещё не проведённые уроки на (ученик, группа).
CREATE TABLE lesson_balances (
    student_id BIGINT NOT NULL REFERENCES students(id),
    group_id   BIGINT NOT NULL REFERENCES groups(id),
    paid       INTEGER NOT NULL DEFAULT 0 CHECK (paid >= 0),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (student_id, group_id)
);

CREATE TABLE salary_schemes (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    center_id          BIGINT NOT NULL REFERENCES centers(id),
    teacher_id         BIGINT NOT NULL REFERENCES staff(id),
    group_id           BIGINT REFERENCES groups(id),   -- NULL — схема по умолчанию для преподавателя
    type               TEXT NOT NULL CHECK (type IN ('fixed', 'perhead', 'revshare')),
    rate_diram         BIGINT NOT NULL DEFAULT 0,       -- fixed: за занятие; perhead: за присутствовавшего
    percent            INTEGER NOT NULL DEFAULT 0,      -- revshare: процент
    lesson_price_diram BIGINT NOT NULL DEFAULT 0,       -- revshare: цена урока на ученика
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uq_salary_scheme ON salary_schemes (teacher_id, COALESCE(group_id, 0));

CREATE TABLE salary_accruals (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    center_id   BIGINT NOT NULL REFERENCES centers(id),
    teacher_id  BIGINT NOT NULL REFERENCES staff(id),
    lesson_id   BIGINT NOT NULL REFERENCES lessons(id),
    amount_diram BIGINT NOT NULL,
    scheme_type TEXT NOT NULL,
    detail      TEXT NOT NULL DEFAULT '',
    at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (lesson_id)
);
CREATE INDEX idx_salary_accruals_teacher ON salary_accruals (teacher_id, at);
