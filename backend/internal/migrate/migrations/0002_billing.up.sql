-- 0002_billing — счета, проводки по балансу, история счетов, идемпотентность.
-- Деньги: BIGINT в дирамах. Время: TIMESTAMPTZ (UTC). Таблицы создаются пустыми — обычный CREATE INDEX.

-- Номера счетов INV-N. Старт с 1045 (демо-счета seed занимают 1042–1044).
CREATE SEQUENCE invoice_number_seq START 1045;

CREATE TABLE invoices (
    id                   TEXT PRIMARY KEY,
    center_id            BIGINT NOT NULL REFERENCES centers(id),
    kind                 TEXT NOT NULL CHECK (kind IN ('renewal', 'plan_change', 'course', 'trial')),
    purpose              TEXT NOT NULL,
    amount_diram         BIGINT NOT NULL CHECK (amount_diram >= 0),
    status               TEXT NOT NULL CHECK (status IN ('pending', 'paid', 'cancelled', 'trial')),
    issued_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    due_at               TIMESTAMPTZ,
    paid_at              TIMESTAMPTZ,
    paid_via             TEXT,             -- manual | balance | online
    method               TEXT,
    channel              TEXT,             -- bank | cash | card | balance | online | promo
    reference            TEXT NOT NULL DEFAULT '',
    reason               TEXT NOT NULL DEFAULT '',
    reminded_at          TIMESTAMPTZ,
    -- Поля смены тарифа (kind = plan_change):
    plan_from_id         TEXT,
    plan_from_name       TEXT,
    plan_to_id           TEXT,
    plan_to_name         TEXT,
    plan_from_expires_at TIMESTAMPTZ,
    deferred             BOOLEAN NOT NULL DEFAULT FALSE,
    course_id            BIGINT,
    -- Платёжные данные (без номеров карт/токенов — только маска и tx id):
    payment              JSONB,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_invoices_center_id ON invoices (center_id);
CREATE INDEX idx_invoices_status ON invoices (status);
CREATE INDEX idx_invoices_kind ON invoices (kind);

-- Журнал проводок по балансу на платформе. Источник истины для баланса; только добавление.
CREATE TABLE ledger (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    center_id           BIGINT NOT NULL REFERENCES centers(id),
    at                  TIMESTAMPTZ NOT NULL DEFAULT now(),
    type                TEXT NOT NULL CHECK (type IN ('topup', 'charge')),
    amount_diram        BIGINT NOT NULL,   -- знаковая: пополнение +, списание -
    balance_after_diram BIGINT NOT NULL,
    method              TEXT NOT NULL DEFAULT '',
    reference           TEXT NOT NULL DEFAULT '',
    invoice_id          TEXT REFERENCES invoices(id),
    actor_name          TEXT NOT NULL DEFAULT '',
    comment             TEXT NOT NULL DEFAULT ''
);
CREATE INDEX idx_ledger_center_at ON ledger (center_id, at DESC, id DESC);

CREATE OR REPLACE FUNCTION ledger_immutable() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'ledger неизменяем: % запрещён (используйте сторно)', TG_OP;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_ledger_no_update
    BEFORE UPDATE OR DELETE ON ledger
    FOR EACH ROW EXECUTE FUNCTION ledger_immutable();

-- История событий счёта (выставлен → напоминание → оплата → применено).
CREATE TABLE invoice_events (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id TEXT NOT NULL REFERENCES invoices(id),
    at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    type       TEXT NOT NULL CHECK (type IN ('issued', 'reminded', 'paid', 'applied', 'cancelled', 'deferred')),
    actor_name TEXT NOT NULL DEFAULT '',
    actor_role TEXT NOT NULL DEFAULT '',
    text       TEXT NOT NULL DEFAULT ''
);
CREATE INDEX idx_invoice_events_invoice ON invoice_events (invoice_id, at);

-- Идемпотентность денежных мутаций: повтор с тем же ключом возвращает прежний ответ.
CREATE TABLE idempotency_keys (
    endpoint    TEXT NOT NULL,
    key         TEXT NOT NULL,
    status_code INTEGER NOT NULL,
    response    JSONB NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (endpoint, key)
);
