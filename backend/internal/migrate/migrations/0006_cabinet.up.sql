-- 0006_cabinet — операционное ядро кабинета центра (CTR-*): профиль, сотрудники, ученики, группы,
-- данные для входа (BR-025). Время — TIMESTAMPTZ, даты курса — DATE. Таблицы пустые — обычный CREATE INDEX.

CREATE TABLE center_profiles (
    center_id    BIGINT PRIMARY KEY REFERENCES centers(id),
    direction    TEXT NOT NULL DEFAULT '',
    description  TEXT NOT NULL DEFAULT '',
    founded_year INTEGER,
    logo         TEXT NOT NULL DEFAULT '',
    banner       TEXT NOT NULL DEFAULT '',
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE staff (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    center_id    BIGINT NOT NULL REFERENCES centers(id),
    name         TEXT NOT NULL,
    role         TEXT NOT NULL CHECK (role IN ('teacher', 'admin', 'manager')),
    phone        TEXT NOT NULL DEFAULT '',
    status       TEXT NOT NULL CHECK (status IN ('active', 'dismissed')),
    hired_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    dismissed_at TIMESTAMPTZ,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_staff_center ON staff (center_id);
CREATE INDEX idx_staff_status ON staff (status);

CREATE TABLE groups (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    center_id    BIGINT NOT NULL REFERENCES centers(id),
    name         TEXT NOT NULL,
    course       TEXT NOT NULL,
    branch       TEXT NOT NULL,
    teacher_id   BIGINT REFERENCES staff(id),
    status       TEXT NOT NULL CHECK (status IN ('active', 'archived')),
    days         TEXT NOT NULL DEFAULT '',  -- индексы дней недели 0–6 через запятую, напр. "0,2,4"
    start_time   TEXT NOT NULL,
    duration_min INTEGER NOT NULL,
    hw_points    INTEGER NOT NULL DEFAULT 0,
    visit_points INTEGER NOT NULL DEFAULT 0,
    exam_day     INTEGER NOT NULL DEFAULT 0,
    exam_points  INTEGER NOT NULL DEFAULT 0,
    capacity     INTEGER NOT NULL DEFAULT 16,
    starts_at    DATE,
    ends_at      DATE,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_groups_center ON groups (center_id);
CREATE INDEX idx_groups_teacher ON groups (teacher_id);

CREATE TABLE students (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    center_id BIGINT NOT NULL REFERENCES centers(id),
    name      TEXT NOT NULL,
    phone     TEXT NOT NULL DEFAULT '',
    status    TEXT NOT NULL CHECK (status IN ('active', 'blocked')),
    group_id  BIGINT REFERENCES groups(id),
    joined_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    coin      INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_students_center ON students (center_id);
CREATE INDEX idx_students_group ON students (group_id);

-- Данные для входа сотрудников и учеников (BR-025): логин уникален на платформе, пароль — bcrypt.
CREATE TABLE access_credentials (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_kind    TEXT NOT NULL CHECK (owner_kind IN ('staff', 'student')),
    owner_id      BIGINT NOT NULL,
    login         TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    must_change   BOOLEAN NOT NULL DEFAULT TRUE,
    issued_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (login),
    UNIQUE (owner_kind, owner_id)
);
