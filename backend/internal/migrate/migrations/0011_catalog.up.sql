-- 0011_catalog — заявки на пробный урок из единого каталога (LRN-CAT-010, CTR-CRM-010).
-- Публичная заявка создаёт лид центра без аккаунтов; центр ведёт статус. Время — TIMESTAMPTZ.

CREATE TABLE catalog_leads (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id  BIGINT NOT NULL REFERENCES centers(id),
    group_id   BIGINT REFERENCES groups(id),              -- желаемая группа (необязательно)
    name       TEXT NOT NULL,
    phone      TEXT NOT NULL,                             -- нормализован E.164
    source     TEXT NOT NULL DEFAULT 'catalog',
    note       TEXT NOT NULL DEFAULT '',
    status     TEXT NOT NULL DEFAULT 'new' CHECK (status IN ('new', 'contacted', 'trial', 'enrolled', 'lost')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_catalog_leads_tenant ON catalog_leads (tenant_id, status);
