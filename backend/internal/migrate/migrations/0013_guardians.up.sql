-- 0013_guardians — связь родитель/опекун ↔ ученик (LRN-PRN-010/020, BR-036).
-- Привязку заводит администратор центра: несколько родителей на ребёнка, один родитель — на разных детей.
-- Время — TIMESTAMPTZ.

CREATE TABLE student_guardians (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id  BIGINT NOT NULL REFERENCES centers(id),
    student_id BIGINT NOT NULL REFERENCES students(id),
    account_id BIGINT NOT NULL REFERENCES accounts(id),
    relation   TEXT NOT NULL DEFAULT '',
    status     TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'revoked')),
    created_by TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uq_guardian ON student_guardians (student_id, account_id);
CREATE INDEX idx_guardians_account ON student_guardians (account_id, status);
CREATE INDEX idx_guardians_tenant ON student_guardians (tenant_id);
