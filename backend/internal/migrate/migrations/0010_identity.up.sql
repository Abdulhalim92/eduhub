-- 0010_identity — единый аккаунт по телефону и членства (ТЗ v2.5, 30-auth-rbac, BR-035/BR-036).
-- Мобильный контур (ученик/родитель): вход по SMS-коду (OTP) и выбор членства. Веб-вход (users) не трогаем.
-- Время — TIMESTAMPTZ в UTC.

-- Аккаунт человека: один на нормализованный номер телефона (E.164).
CREATE TABLE accounts (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone        TEXT NOT NULL UNIQUE,                 -- нормализован E.164
    display_name TEXT NOT NULL DEFAULT '',
    locale       TEXT NOT NULL DEFAULT 'ru' CHECK (locale IN ('ru', 'tg')),
    status       TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'blocked')),
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Членство: роль человека в центре. У человека может быть несколько ролей (BR-040),
-- по одной строке на роль. Роль задаётся членством, не аккаунтом (BR-035).
CREATE TABLE memberships (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES accounts(id),
    tenant_id  BIGINT NOT NULL REFERENCES centers(id),
    role       TEXT NOT NULL CHECK (role IN ('owner', 'admin', 'cashier', 'teacher', 'student', 'parent')),
    status     TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'revoked')),
    branch_id  BIGINT,                                 -- обязателен для admin/cashier (BR-038), проверяется в сервисе
    created_by TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uq_membership ON memberships (account_id, tenant_id, role);
CREATE INDEX idx_memberships_account ON memberships (account_id);
CREATE INDEX idx_memberships_tenant ON memberships (tenant_id, role);

-- Привязка ученика к аккаунту (NULL — теневой профиль ребёнка без своего входа, LRN-PRN-010).
ALTER TABLE students ADD COLUMN account_id BIGINT REFERENCES accounts(id);
CREATE INDEX idx_students_account ON students (account_id);

-- Одноразовые коды входа по SMS (SYS-ACC-030): хэш кода, срок жизни, счётчик попыток.
CREATE TABLE otp_codes (
    phone        TEXT PRIMARY KEY,
    code_hash    TEXT NOT NULL,
    expires_at   TIMESTAMPTZ NOT NULL,
    attempts     INTEGER NOT NULL DEFAULT 0,
    requested_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
