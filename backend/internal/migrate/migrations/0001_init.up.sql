-- 0001_init — начальная схема платформы SuperAdmin.
-- Деньги: BIGINT в дирамах (1 сомони = 100 дирам, money.md). Время: TIMESTAMPTZ (UTC).
-- Индексы здесь обычные CREATE INDEX: таблицы создаются пустыми, блокировать нечего.
-- CONCURRENTLY требуется только для будущих миграций по заполненным таблицам (migrations.md).

CREATE TABLE plans (
    id               TEXT PRIMARY KEY,
    name             TEXT NOT NULL UNIQUE,
    price_diram      BIGINT NOT NULL DEFAULT 0 CHECK (price_diram >= 0),
    limit_staff      INTEGER NOT NULL CHECK (limit_staff >= 1),
    limit_storage_gb INTEGER NOT NULL CHECK (limit_storage_gb >= 1),
    limit_branches   INTEGER NOT NULL CHECK (limit_branches >= 1),
    module_payroll   BOOLEAN NOT NULL DEFAULT FALSE,
    module_inventory BOOLEAN NOT NULL DEFAULT FALSE,
    module_crm       BOOLEAN NOT NULL DEFAULT FALSE,
    module_geo       BOOLEAN NOT NULL DEFAULT TRUE,
    active           BOOLEAN NOT NULL DEFAULT TRUE,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE managers (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name   TEXT NOT NULL UNIQUE,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE centers (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                  TEXT NOT NULL UNIQUE,
    city                  TEXT NOT NULL,
    owner                 TEXT NOT NULL,
    phone                 TEXT NOT NULL,
    plan_id               TEXT NOT NULL REFERENCES plans(id),
    balance_diram         BIGINT NOT NULL DEFAULT 0,
    overdraft_limit_diram BIGINT NOT NULL DEFAULT 0 CHECK (overdraft_limit_diram >= 0),
    staff_used            INTEGER NOT NULL DEFAULT 0 CHECK (staff_used >= 0),
    storage_used_gb       INTEGER NOT NULL DEFAULT 0 CHECK (storage_used_gb >= 0),
    branches_used         INTEGER NOT NULL DEFAULT 0 CHECK (branches_used >= 0),
    last_login_at         TIMESTAMPTZ,            -- NULL => ещё не входил (neverLogged)
    lessons_7d            INTEGER NOT NULL DEFAULT 0,
    status                TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'blocked')),
    expires_at            TIMESTAMPTZ,            -- NULL => подписка не истекает (бесплатный тариф)
    manager_id            BIGINT REFERENCES managers(id),
    contacted             BOOLEAN NOT NULL DEFAULT FALSE,
    reminded              BOOLEAN NOT NULL DEFAULT FALSE,
    created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_centers_plan_id ON centers (plan_id);
CREATE INDEX idx_centers_status ON centers (status);
CREATE INDEX idx_centers_city ON centers (city);

-- Пользователи-принципалы. tenant_id изолирует данные центра (BR-022/NFR-SEC-010);
-- NULL для SuperAdmin. Логин хранится в нижнем регистре (BR-025, регистр не различается).
CREATE TABLE users (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login                TEXT NOT NULL UNIQUE CHECK (login ~ '^[a-z0-9][a-z0-9._-]{3,31}$'),
    password_hash        TEXT NOT NULL,
    role                 TEXT NOT NULL CHECK (role IN ('superadmin', 'center_admin', 'cashier', 'teacher', 'student', 'parent')),
    name                 TEXT NOT NULL,
    tenant_id            BIGINT REFERENCES centers(id),
    must_change_password BOOLEAN NOT NULL DEFAULT TRUE,
    active               BOOLEAN NOT NULL DEFAULT TRUE,
    password_changed_at  TIMESTAMPTZ,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_users_tenant_id ON users (tenant_id);

-- Блокировка подбора пароля: 5 неудач подряд → блок логина на 15 минут (BR-025, SYS-ACC-020).
CREATE TABLE login_attempts (
    login        TEXT PRIMARY KEY,
    fail_count   INTEGER NOT NULL DEFAULT 0,
    locked_until TIMESTAMPTZ,
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Неизменяемый журнал аудита (BR-010, NFR-SEC-020): только добавление.
-- Триггер запрещает UPDATE/DELETE на уровне БД; финансовые записи отменяются сторно, не удалением.
CREATE TABLE audit_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    actor_name  TEXT NOT NULL,
    actor_role  TEXT NOT NULL,
    ip          TEXT,
    device      TEXT,
    action      TEXT NOT NULL,
    entity_type TEXT NOT NULL,
    entity_id   TEXT,
    entity_name TEXT,
    before      JSONB,
    after       JSONB,
    reason      TEXT
);
CREATE INDEX idx_audit_log_at ON audit_log (at DESC);
CREATE INDEX idx_audit_log_entity ON audit_log (entity_type, entity_id);

CREATE OR REPLACE FUNCTION audit_log_immutable() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'audit_log неизменяем: % запрещён', TG_OP;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_audit_log_no_update
    BEFORE UPDATE OR DELETE ON audit_log
    FOR EACH ROW EXECUTE FUNCTION audit_log_immutable();
