-- 0008_journal — электронный журнал (LRN-TCH): занятия, посещаемость, смены, баллы за успехи, тесты.
-- Поведение проектируется от спеки (прототипа нет). coin — внутренние баллы (INT). Время — TIMESTAMPTZ.

-- Конкретные занятия группы (гибрид: авто-слоты из расписания + внеплановые вручную).
CREATE TABLE lessons (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    center_id    BIGINT NOT NULL REFERENCES centers(id),
    group_id     BIGINT NOT NULL REFERENCES groups(id),
    teacher_id   BIGINT REFERENCES staff(id),
    date         DATE NOT NULL,
    start_time   TEXT NOT NULL DEFAULT '',
    duration_min INTEGER NOT NULL DEFAULT 0,
    status       TEXT NOT NULL CHECK (status IN ('planned', 'conducted')),
    ad_hoc       BOOLEAN NOT NULL DEFAULT FALSE,
    conducted_at TIMESTAMPTZ,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (group_id, date)
);
CREATE INDEX idx_lessons_center ON lessons (center_id);
CREATE INDEX idx_lessons_group_date ON lessons (group_id, date);

CREATE TABLE attendance (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lesson_id  BIGINT NOT NULL REFERENCES lessons(id),
    student_id BIGINT NOT NULL REFERENCES students(id),
    status     TEXT NOT NULL CHECK (status IN ('present', 'late', 'absent', 'excused')),
    late_min   INTEGER NOT NULL DEFAULT 0,
    grade      INTEGER,
    tags       TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (lesson_id, student_id)
);
CREATE INDEX idx_attendance_lesson ON attendance (lesson_id);
CREATE INDEX idx_attendance_student ON attendance (student_id);

CREATE TABLE teacher_shifts (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    center_id  BIGINT NOT NULL REFERENCES centers(id),
    teacher_id BIGINT NOT NULL REFERENCES staff(id),
    branch     TEXT NOT NULL DEFAULT '',
    started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    gps_lat    DOUBLE PRECISION NOT NULL DEFAULT 0,
    gps_lng    DOUBLE PRECISION NOT NULL DEFAULT 0,
    ended_at   TIMESTAMPTZ
);
CREATE INDEX idx_teacher_shifts_center ON teacher_shifts (center_id);

-- Бюджет бонусных баллов на группу (LRN-TCH-040).
CREATE TABLE group_point_budgets (
    group_id   BIGINT PRIMARY KEY REFERENCES groups(id),
    period     TEXT NOT NULL CHECK (period IN ('week', 'month')),
    amount     INTEGER NOT NULL CHECK (amount >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE point_grants (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    center_id  BIGINT NOT NULL REFERENCES centers(id),
    group_id   BIGINT NOT NULL REFERENCES groups(id),
    student_id BIGINT NOT NULL REFERENCES students(id),
    lesson_id  BIGINT REFERENCES lessons(id),
    amount     INTEGER NOT NULL,
    reason     TEXT NOT NULL DEFAULT '',
    at         TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_point_grants_group_at ON point_grants (group_id, at);

-- Тесты с автопроверкой (LRN-TCH-030). questions: [{text, options[], correct}].
CREATE TABLE tests (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    center_id  BIGINT NOT NULL REFERENCES centers(id),
    group_id   BIGINT REFERENCES groups(id),
    lesson_id  BIGINT REFERENCES lessons(id),
    title      TEXT NOT NULL,
    questions  JSONB NOT NULL DEFAULT '[]',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_tests_center ON tests (center_id);

CREATE TABLE test_submissions (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    test_id    BIGINT NOT NULL REFERENCES tests(id),
    student_id BIGINT NOT NULL REFERENCES students(id),
    answers    JSONB NOT NULL DEFAULT '[]',
    score_pct  INTEGER NOT NULL DEFAULT 0,
    graded_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (test_id, student_id)
);
