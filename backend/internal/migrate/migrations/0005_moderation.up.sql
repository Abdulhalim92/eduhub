-- 0005_moderation — заявки центров на публикацию филиалов в каталоге и очередь модерации (PLT-MOD).
-- gps — точка, указанная центром; geo — точка геокодера. Время — TIMESTAMPTZ. Таблица пустая — обычный CREATE INDEX.

CREATE TABLE branch_submissions (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    center_id    BIGINT NOT NULL REFERENCES centers(id),
    branch       TEXT NOT NULL,
    city         TEXT NOT NULL,
    district     TEXT NOT NULL DEFAULT 'Центр',
    address      TEXT NOT NULL,
    phone        TEXT NOT NULL DEFAULT '',
    gps_lat      DOUBLE PRECISION NOT NULL,
    gps_lng      DOUBLE PRECISION NOT NULL,
    geo_lat      DOUBLE PRECISION NOT NULL,
    geo_lng      DOUBLE PRECISION NOT NULL,
    desc_ru      TEXT NOT NULL DEFAULT '',
    desc_tj      TEXT NOT NULL DEFAULT '',
    desc_en      TEXT NOT NULL DEFAULT '',
    status       TEXT NOT NULL CHECK (status IN ('pending', 'published', 'returned', 'rejected')),
    reason       TEXT NOT NULL DEFAULT '',
    gps_ok       BOOLEAN NOT NULL DEFAULT FALSE,
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    submitted_by TEXT NOT NULL DEFAULT '',
    decided_at   TIMESTAMPTZ,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_branch_submissions_center ON branch_submissions (center_id);
CREATE INDEX idx_branch_submissions_status ON branch_submissions (status);
