-- 0007_coins — поощрения за coin (CTR-RWD) и автоправила начисления coin (CTR-CIN).
-- coin — внутренние баллы центра (не деньги), INT. Таблицы пустые — обычный CREATE INDEX.

CREATE TABLE rewards (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    center_id  BIGINT NOT NULL REFERENCES centers(id),
    name       TEXT NOT NULL,
    category   TEXT NOT NULL,
    price      INTEGER NOT NULL CHECK (price >= 1),
    status     TEXT NOT NULL CHECK (status IN ('active', 'archived')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_rewards_center ON rewards (center_id);

CREATE TABLE coin_rules (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    center_id  BIGINT NOT NULL REFERENCES centers(id),
    name       TEXT NOT NULL,
    scope      TEXT NOT NULL CHECK (scope IN ('academy', 'course', 'group')),
    threshold  INTEGER NOT NULL CHECK (threshold BETWEEN 1 AND 100),
    coin       INTEGER NOT NULL CHECK (coin BETWEEN 1 AND 10000),
    active     BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_coin_rules_center ON coin_rules (center_id);
